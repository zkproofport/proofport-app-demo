export function translateCu(
  language: CuLanguage,
  message: string,
  values: Record<string, string | number> = {}
) {
  let result = message;
  if (language === 'en' && /[가-힣]/.test(message)) {
    const translated = CU_EN[message];
    if (translated === undefined) throw new Error(`Missing CU translation: ${message}`);
    result = translated;
  }
  return result.replace(/\{(\w+)\}/g, (_, key: string) => {
    if (!(key in values)) throw new Error(`Missing CU translation value: ${key}`);
    return String(values[key]);
  });
}
